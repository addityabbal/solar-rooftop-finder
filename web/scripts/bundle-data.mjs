// Writes lib/bundledData.ts: every stored scan and its pipeline events, imported as modules.
// Cloudflare Workers have no project files on disk, so the deployed app reads showcase
// scans from the bundle instead of data/scans/*.json. Runs before dev and build.
import { readdirSync, writeFileSync, existsSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const list = (dir, suffix) =>
  existsSync(path.join(root, dir))
    ? readdirSync(path.join(root, dir)).filter((f) => /^[1-9][0-9]{5}/.test(f) && f.endsWith(suffix)).sort()
    : [];

const scans = list("data/scans", ".json");
const events = list("data/campaign", ".events.json");
const lines = [
  "// Generated by scripts/bundle-data.mjs. Do not edit.",
  'import type { CampaignEvent, Scan } from "./types";',
  ...scans.map((f, i) => `import scan${i} from "../data/scans/${f}";`),
  ...events.map((f, i) => `import events${i} from "../data/campaign/${f}";`),
  "",
  "export const bundledScans: Record<string, Scan> = {",
  ...scans.map((f, i) => `  "${f.slice(0, 6)}": scan${i} as unknown as Scan,`),
  "};",
  "",
  "export const bundledEvents: Record<string, CampaignEvent[]> = {",
  ...events.map((f, i) => `  "${f.slice(0, 6)}": events${i} as unknown as CampaignEvent[],`),
  "};",
  "",
];
writeFileSync(path.join(root, "lib", "bundledData.ts"), lines.join("\n"));
console.log(`bundled ${scans.length} scan(s), ${events.length} event log(s)`);
